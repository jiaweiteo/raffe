-- Private schema: browser Supabase clients receive no access to raffle records.
CREATE SCHEMA IF NOT EXISTS raffle;
REVOKE ALL ON SCHEMA raffle FROM PUBLIC, anon, authenticated;
SET search_path = raffle, pg_catalog;
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS guests(
 id TEXT PRIMARY KEY, name TEXT NOT NULL, remarks TEXT, guest_of TEXT,
 table_no TEXT, source_row INTEGER NOT NULL UNIQUE, deleted_at TEXT);
CREATE TABLE IF NOT EXISTS payments(
 id TEXT PRIMARY KEY, source_key TEXT UNIQUE, source TEXT NOT NULL,
 amount_cents INTEGER NOT NULL CHECK(amount_cents>0), bank_time TEXT,
 account_suffix TEXT, created_at TEXT NOT NULL, confirmed_at TEXT,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','ignored','reversed')),
 note TEXT NOT NULL DEFAULT '', source_link TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS allocations(
 id TEXT PRIMARY KEY, payment_id TEXT NOT NULL REFERENCES payments(id),
 guest_id TEXT NOT NULL REFERENCES guests(id), amount_cents INTEGER NOT NULL CHECK(amount_cents>=0),
 count INTEGER NOT NULL CHECK(count>0), first_ticket INTEGER NOT NULL,
 CHECK(first_ticket>=52000001 AND first_ticket+count-1<=52001500));
CREATE TABLE IF NOT EXISTS tickets(
 number INTEGER PRIMARY KEY CHECK(number BETWEEN 52000001 AND 52001500),
 allocation_id TEXT NOT NULL REFERENCES allocations(id), status TEXT NOT NULL CHECK(status IN ('active','void')));
CREATE TABLE IF NOT EXISTS audit(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT NOT NULL,
 action TEXT NOT NULL, payment_id TEXT, details TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS mail_issues(
 message_id TEXT PRIMARY KEY, received_at TEXT NOT NULL, error TEXT NOT NULL,
 source_link TEXT NOT NULL, resolved INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS workbook_template(
 id INTEGER PRIMARY KEY CHECK(id=1), contents BYTEA NOT NULL, sha256 TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS allocations_payment ON allocations(payment_id);
CREATE INDEX IF NOT EXISTS allocations_guest ON allocations(guest_id);
CREATE INDEX IF NOT EXISTS tickets_allocation ON tickets(allocation_id);
REVOKE ALL ON ALL TABLES IN SCHEMA raffle FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA raffle FROM PUBLIC, anon, authenticated;
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE guests ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE mail_issues ENABLE ROW LEVEL SECURITY;
ALTER TABLE workbook_template ENABLE ROW LEVEL SECURITY;
